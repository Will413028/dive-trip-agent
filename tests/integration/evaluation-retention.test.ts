import { expect, test } from 'vitest';
import { withDatabase, testDatabaseUrl } from '../support/database';
import { database, makePool } from '../../src/server/db';
import { withAdkSchemaLock } from '../../src/server/adk-schema-lock';

test('evaluation export failure can retain its isolated DB, while normal success still cleans up', async () => {
  let retained = '', successful = '', ordinaryFailure = '';
  const admin = makePool(testDatabaseUrl());
  try {
    await expect(withDatabase(async () => {
      retained = (await database().query('SELECT current_schema() AS name')).rows[0].name;
      throw new Error('EVAL_PRIVATE_USAGE_EXPORT_FAILED');
    }, { retainOnFailure: true })).rejects.toThrow('EVAL_PRIVATE_USAGE_EXPORT_FAILED');
    expect(retained).toMatch(/^test_[a-f0-9]{32}$/);
    expect((await admin.query('SELECT to_regclass($1) AS name', [`${retained}.model_calls`])).rows[0].name).not.toBeNull();
    await withDatabase(async () => {
      successful = (await database().query('SELECT current_schema() AS name')).rows[0].name;
    }, { retainOnFailure: true });
    expect((await admin.query('SELECT to_regclass($1) AS name', [`${successful}.model_calls`])).rows[0].name).toBeNull();
    await expect(withDatabase(async () => {
      ordinaryFailure = (await database().query('SELECT current_schema() AS name')).rows[0].name;
      throw new Error('ORDINARY_TEST_FAILURE');
    })).rejects.toThrow('ORDINARY_TEST_FAILURE');
    expect((await admin.query('SELECT to_regclass($1) AS name', [`${ordinaryFailure}.model_calls`])).rows[0].name).toBeNull();
  } finally {
    // Only clean the schema generated by this test, never an actual retained campaign.
    if (/^test_[a-f0-9]{32}$/.test(retained)) {
      const client = await admin.connect();
      try { await withAdkSchemaLock(client, async () => {
        await client.query(`DROP SCHEMA IF EXISTS "${retained}_adk" CASCADE`);
        await client.query(`DROP SCHEMA "${retained}" CASCADE`);
      }); } finally { client.release(); }
    }
    await admin.end();
  }
}, 30_000);
